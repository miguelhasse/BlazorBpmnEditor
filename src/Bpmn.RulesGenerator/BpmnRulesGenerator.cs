using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Hasseware.AspNetCore.Components.Bpmn.RulesGenerator;

/// <summary>
/// Reads rules/bpmn-rules.json (wired into the consuming project as an AdditionalFile — see
/// src/Bpmn/Hasseware.AspNetCore.Components.Bpmn.csproj) and emits a typed <c>BpmnRules</c>
/// catalog: one <c>BpmnRuleInfo</c> constant per rule (id/scope/connectorKind/severity/message),
/// plus a <c>BpmnRules.All</c> list. <c>ConnectorKind</c> is <c>""</c> for document-scope
/// structural rules that aren't about one connector kind (e.g. <c>D001</c>).
///
/// This is metadata only: it does not evaluate predicates. TypeScript evaluates the
/// <c>live</c>-scope rules during a connection gesture, because a drag has to be judged at
/// pointer speed; C# evaluates the <c>document</c>-scope rules (specification sections 5.2-5.5),
/// because it owns the document lifecycle and the semantic model of record. This catalog exists so
/// that neither side hand-duplicates a rule id, message or severity. See rules/README.md.
/// </summary>
[Generator]
public sealed class BpmnRulesGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var rulesFiles = context.AdditionalTextsProvider
            .Where(static file => System.IO.Path.GetFileName(file.Path).Equals("bpmn-rules.json", System.StringComparison.OrdinalIgnoreCase))
            .Collect();

        context.RegisterSourceOutput(rulesFiles, static (spc, files) =>
        {
            // No AdditionalFiles wired up (a consuming project that hasn't referenced the rule
            // table yet) — nothing to generate, not an error.
            if (files.IsDefaultOrEmpty) return;

            var text = files[0].GetText(spc.CancellationToken)?.ToString();
            if (text is null) return;

            if (MiniJson.Parse(text) is not Dictionary<string, object?> root ||
                root.TryGetValue("rules", out var rulesValue) is false ||
                rulesValue is not List<object?> rules)
            {
                spc.ReportDiagnostic(Diagnostic.Create(MalformedRuleTable, Location.None, files[0].Path));
                return;
            }

            spc.AddSource("BpmnRules.g.cs", SourceText.From(GenerateSource(rules), Encoding.UTF8));
        });
    }

    private static readonly DiagnosticDescriptor MalformedRuleTable = new(
        id: "BPMNRULES001",
        title: "Malformed BPMN rule table",
        messageFormat: "'{0}' could not be parsed as the expected {{ rules: [...] }} shape",
        category: "Hasseware.AspNetCore.Components.Bpmn.RulesGenerator",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static string GenerateSource(List<object?> rules)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by Bpmn.RulesGenerator from rules/bpmn-rules.json. Do not edit by hand.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace Hasseware.AspNetCore.Components.Bpmn.Configuration;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>One entry from rules/bpmn-rules.json — see BpmnRules for the full catalog.</summary>");
        sb.AppendLine("public sealed record BpmnRuleInfo(string Id, string Scope, string ConnectorKind, string Severity, string Message);");
        sb.AppendLine();
        sb.AppendLine("/// <summary>The shared connection-rule catalog, generated from rules/bpmn-rules.json.</summary>");
        sb.AppendLine("public static class BpmnRules");
        sb.AppendLine("{");

        var fieldNames = new List<string>();
        foreach (var ruleObj in rules)
        {
            if (ruleObj is not Dictionary<string, object?> rule) continue;
            var id = (string)rule["id"]!;
            var scope = (string)rule["scope"]!;
            // Absent for document-scope structural rules that aren't about one connector kind (e.g. D001).
            var connectorKind = rule.TryGetValue("connectorKind", out var connectorKindValue) && connectorKindValue is string connectorKindString
                ? connectorKindString
                : "";
            var severity = (string)rule["severity"]!;
            var message = (string)rule["message"]!;
            var fieldName = ToFieldName(id);
            fieldNames.Add(fieldName);

            // Emit documentation too: the consuming project builds with warnings as errors and
            // an XML documentation file, so an undocumented public member fails the build.
            sb.AppendLine($"    /// <summary>{EscapeXml(id)}: {EscapeXml(message)}</summary>");
            sb.AppendLine(
                $"    public static readonly BpmnRuleInfo {fieldName} = new(\"{Escape(id)}\", \"{Escape(scope)}\", " +
                $"\"{Escape(connectorKind)}\", \"{Escape(severity)}\", \"{Escape(message)}\");");
        }

        sb.AppendLine();
        sb.AppendLine("    /// <summary>Every rule in the catalog, in declaration order.</summary>");
        sb.Append("    public static readonly System.Collections.Generic.IReadOnlyList<BpmnRuleInfo> All = new BpmnRuleInfo[] { ");
        sb.Append(string.Join(", ", fieldNames));
        sb.AppendLine(" };");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string ToFieldName(string ruleId) => ruleId.Replace("-", "");

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    /// <summary>Escapes a value for use inside an XML documentation comment.</summary>
    private static string EscapeXml(string value) =>
        value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
