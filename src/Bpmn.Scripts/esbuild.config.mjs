import * as esbuild from 'esbuild';
import { glob } from 'glob';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

/** esbuild outputs and CSS @import statements both want forward slashes, on every OS. */
const toPosix = (p) => p.split(path.sep).join('/');

const pkg = JSON.parse(await readFile('./package.json', 'utf8'));

const rawBuildMode = process.argv.find((a) => a.startsWith('--build-mode='))?.split('=')[1];
const buildMode = rawBuildMode === 'Release' ? 'Release' : 'Debug';
const isDebug = buildMode === 'Debug';

// ---------------------------------------------------------------------------
// BuildConstants.ts — generated, committed, rewritten only when the mode changes
// so it does not churn the working tree on every build.
// ---------------------------------------------------------------------------
const constantsFile = path.resolve('src/BuildConstants.ts');
const constantsContent =
  `// This file is generated by a tool. Do not change!\n` +
  `export const BUILD_MODE: 'Debug' | 'Release' = '${buildMode}';\n`;
const currentConstants = await readFile(constantsFile, 'utf8').catch(() => '');
if (currentConstants !== constantsContent) {
  await writeFile(constantsFile, constantsContent, 'utf8');
}

await mkdir('dist', { recursive: true });

// ---------------------------------------------------------------------------
// JS — the Blazor static web asset the BpmnCanvas component imports.
// ---------------------------------------------------------------------------
const jsResult = await esbuild.build({
  entryPoints: [pkg.source],
  bundle: true,
  minify: !isDebug,
  sourcemap: isDebug,
  logLevel: 'info',
  target: 'es2022',
  format: 'esm',
  outfile: pkg.main,
  legalComments: 'none',
  metafile: true,
});

// ---------------------------------------------------------------------------
// CSS — one bundle for the whole library. Scoped CSS is disabled in the csproj
// (DisableScopedCssBundling/ScopedCssEnabled), so these are plain stylesheets
// rather than per-component scoped ones, and they live in the library's
// wwwroot/css as ordinary static web assets. This collects them into the single
// bundle a consumer actually links.
// ---------------------------------------------------------------------------
const componentCss = (await glob(pkg.cssFiles, { posix: true })).sort();
const cssEntryFile = path.resolve('dist/.css-entry.css');
const cssEntryDir = path.dirname(cssEntryFile);

// NOTE: @joint/core 4.x ships no stylesheet — v4 moved paper/tool styling into the
// views themselves — so there is nothing to import from the package here. Everything
// below is this library's own component CSS.
const imports = [];
for (const file of componentCss) {
  const relative = toPosix(path.relative(cssEntryDir, path.resolve(file)));
  imports.push(`@import '${relative.startsWith('.') ? relative : `./${relative}`}';`);
}

let cssResult;
try {
  await writeFile(cssEntryFile, `${imports.join('\n')}\n`, 'utf8');
  cssResult = await esbuild.build({
    entryPoints: [cssEntryFile],
    bundle: true,
    minify: !isDebug,
    logLevel: 'info',
    outfile: pkg.cssBundle,
    loader: { '.svg': 'dataurl', '.woff2': 'file', '.woff': 'file', '.png': 'dataurl' },
    metafile: true,
  });
} finally {
  await rm(cssEntryFile, { force: true });
}

// ---------------------------------------------------------------------------
// Manifest — consumed by scripts/verify-bundle.mjs and useful for size budgets.
// ---------------------------------------------------------------------------
const outputs = {};
for (const [file, meta] of Object.entries({ ...jsResult.metafile.outputs, ...cssResult.metafile.outputs })) {
  outputs[toPosix(file)] = meta.bytes;
}

await writeFile(
  'dist/bundle-manifest.json',
  `${JSON.stringify({ buildMode, generatedAt: new Date().toISOString(), componentCss, outputs }, null, 2)}\n`,
  'utf8',
);
